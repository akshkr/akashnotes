#!/usr/bin/env python3
"""
Build the course index (v2/index.md) from SYLLABUS_V2.md and tools/day_map.json.

Usage:  python3 tools/build_index.py [--out v2/index.md]

Regenerate after any syllabus or day-map change; the index is derived, never hand-edited.
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def main(argv: list[str]) -> int:
    course = ROOT / "v2" if (ROOT / "v2").is_dir() else ROOT   # staging tree before cutover, repo root after
    out = Path(next((a.split("=", 1)[1] for a in argv if a.startswith("--out=")), str(course / "index.md")))
    syl = (ROOT / "SYLLABUS_V2.md").read_text(encoding="utf-8")
    dm = {d["day"]: d for d in json.loads((ROOT / "tools/day_map.json").read_text())}
    phases = re.findall(r"^## (Phase \d+: .+)$", syl, re.M)
    entries = {}
    for m in re.finditer(r"^### D(\d{3}) · (.+?) · `[^`]+`.*?$(.*?)(?=^### D\d{3} |^## |\Z)", syl, re.M | re.S):
        day, body = int(m.group(1)), m.group(3)
        why = re.search(r"^- \*\*Why:\*\* (.+)$", body, re.M)
        build = re.search(r"^- \*\*Build:\*\* (.+)$", body, re.M)
        entries[day] = (m.group(2).strip(), why.group(1).strip() if why else "", build.group(1).strip() if build else "")
    rel = lambda d: str(Path(dm[d]["path"].removeprefix("v2/")))
    lines = [
        "# 100 Days: From Software Engineer (or Fresher) to AI Engineer: Day-by-Day Index",
        "",
        "> Generated by `tools/build_index.py` from `SYLLABUS_V2.md`. Don't edit by hand.",
        "> New here? Start with [Day 1](" + rel(1) + "). Short on a prerequisite? See the "
        "[appendix primers](#appendix-primers-outside-the-100-days). Model IDs, prices and library notes "
        "live in `REFERENCE.md`.",
        "",
        "Every day is a **~2-hour core path**: read, run the code, do the exercises. Optional *Go Deeper* "
        "sections hold the advanced material. You build one product, **Atlas**, across five releases "
        "(R1–R5) on the fictional **Orbit** dataset.",
        "",
    ]
    phase_of = {}
    for ph in phases:
        n = int(re.match(r"Phase (\d+)", ph).group(1))
        days = [d for d in dm if dm[d]["phase"] == n]
        for d in days:
            phase_of[d] = ph
    current = None
    for d in sorted(entries):
        ph = phase_of.get(d)
        if ph != current:
            current = ph
            span = [x for x in dm if phase_of.get(x) == ph]
            lines += ["---", "", f"## {ph} (Days {min(span)}–{max(span)})", ""]
        title, why, build = entries[d]
        cap = " 🏁" if title.startswith("Capstone") else ""
        lines.append(f"**[Day {d:03d}: {title}]({rel(d)})**{cap}  ")
        lines.append(f"{why}" + (f" *You build:* {build}" if build else ""))
        lines.append("")
    prim = re.search(r"^## Appendix primers.*?$(.*?)(?=^## |\Z)", syl, re.M | re.S)
    if prim:
        lines += ["---", "", "## Appendix primers (outside the 100 days)", ""]
        files = sorted((course / "Appendix_Primers").glob("*.md"))
        for f in files:
            t = re.search(r"^# (.+)$", f.read_text(encoding="utf-8"), re.M)
            lines.append(f"- [{t.group(1) if t else f.stem}](Appendix_Primers/{f.name})")
        lines.append("")
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {out} ({len(entries)} days, {len(phases)} phases)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
